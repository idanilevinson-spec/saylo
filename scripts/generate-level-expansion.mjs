// Writes supabase/seed/026_level_expansion.sql from the authored content in
// scripts/content/levelExpansion.mjs. Generated, so every MCQ's options and
// correctIndex are right by construction (same approach as seeds 010/014).
// Run: node scripts/generate-level-expansion.mjs [path/to/existing-headwords.txt]
// The optional file (one lowercase headword per line) makes the script fail
// on any word that already exists in another topic.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { VOCAB_TOPICS, WRITING_PROMPTS, SCENARIOS, GRAMMAR_TOPICS } from "./content/levelExpansion.mjs";

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const dollar = (s) => {
  if (s.includes("$$")) throw new Error("body contains $$");
  return `$$${s}$$`;
};
const json = (o) => q(JSON.stringify(o));
const errors = [];

// ---- validation ----
const existing = process.argv[2] && existsSync(process.argv[2])
  ? new Set(readFileSync(process.argv[2], "utf8").split(/\r?\n/).filter(Boolean))
  : null;
const seen = new Set();
for (const t of VOCAB_TOPICS) {
  if (t.words.length < 8) errors.push(`${t.slug}: only ${t.words.length} words`);
  for (const w of t.words) {
    if (w.length !== 6 || w.some((x) => !x)) errors.push(`${t.slug}/${w[0]}: incomplete row`);
    const key = w[0].toLowerCase();
    if (seen.has(key)) errors.push(`duplicate headword in this seed: ${w[0]}`);
    seen.add(key);
    if (existing?.has(key)) errors.push(`headword already in the database: ${w[0]}`);
    if (!w[4].toLowerCase().includes(key.split(" ")[0].slice(0, 4))) errors.push(`${w[0]}: example doesn't use the word`);
  }
}
for (const g of GRAMMAR_TOPICS) {
  for (const [sentence, answer] of g.fill) {
    if ((sentence.match(/___/g) ?? []).length !== 1) errors.push(`${g.slug}: "${sentence}" needs exactly one ___`);
    if (!answer) errors.push(`${g.slug}: empty answer`);
  }
}
if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}

// ---- SQL ----
const out = [];
out.push(`-- Level expansion (generated by scripts/generate-level-expansion.mjs from
-- scripts/content/levelExpansion.mjs — edit the content there, not here).
-- Fills the levels the content inventory showed were thin:
--   vocabulary: ${VOCAB_TOPICS.length} new topics (${VOCAB_TOPICS.reduce((n, t) => n + t.words.length, 0)} words, with IPA, example and English definition),
--   grammar: ${GRAMMAR_TOPICS.length} new topics with a lesson and practice,
--   writing: ${WRITING_PROMPTS.length} new prompts (first ever at C1/C2),
--   speaking: ${SCENARIOS.length} new scenarios (first ever at C1/C2).
-- All content is original. Safe to re-run: rows are upserted by slug, or
-- cleared and reinserted for these topics; writing prompts insert only if
-- the same prompt text isn't there yet.
`);

// Vocabulary topics + items
out.push(`insert into public.topics (slug, name_he, name_en, cefr_level, sort_order) values
${VOCAB_TOPICS.map((t) => `  (${q(t.slug)}, ${q(t.name_he)}, ${q(t.name_en)}, ${q(t.level)}, ${t.sort})`).join(",\n")}
on conflict (slug) do update set
  name_he = excluded.name_he,
  name_en = excluded.name_en,
  cefr_level = excluded.cefr_level,
  sort_order = excluded.sort_order;
`);
const slugList = VOCAB_TOPICS.map((t) => q(t.slug)).join(", ");
out.push(`delete from public.exercises where topic_id in (select id from public.topics where slug in (${slugList}));
delete from public.vocabulary_items where topic_id in (select id from public.topics where slug in (${slugList}));
`);
out.push(`insert into public.vocabulary_items (topic_id, headword, ipa, part_of_speech, translation_he, example_en, definition_en, cefr_level, sort_order)
select t.id, v.headword, v.ipa, v.part_of_speech, v.translation_he, v.example_en, v.definition_en, t.cefr_level, v.sort_order
from public.topics t
join (values
${VOCAB_TOPICS.flatMap((t) =>
  t.words.map(
    ([hw, ipa, pos, he, ex, def], i) => `  (${q(t.slug)}, ${q(hw)}, ${q(ipa)}, ${q(pos)}, ${q(he)}, ${q(ex)}, ${q(def)}, ${i + 1})`,
  ),
).join(",\n")}
) as v(topic_slug, headword, ipa, part_of_speech, translation_he, example_en, definition_en, sort_order)
  on t.slug = v.topic_slug;
`);

// One MCQ per word (Hebrew → English), distractors from the same topic,
// correct position rotating so it is never always first.
const mcqRows = [];
for (const t of VOCAB_TOPICS) {
  t.words.forEach(([hw, , , he], i) => {
    const others = t.words.map((w) => w[0]).filter((w) => w !== hw);
    // Deterministic but varied: three distractors starting at an offset.
    const distractors = [0, 1, 2].map((k) => others[(i * 3 + k * 2) % others.length]);
    if (new Set(distractors).size < 3) throw new Error(`distractors collide for ${hw}`);
    const correctIndex = i % 4;
    const options = [...distractors];
    options.splice(correctIndex, 0, hw);
    mcqRows.push(`  (${q(t.slug)}, ${q(hw)}, ${json({ prompt: `מה המילה באנגלית עבור "${he}"?`, options, correctIndex })}, ${i + 1})`);
  });
}
out.push(`insert into public.exercises (type, skill_area, topic_id, vocabulary_item_id, cefr_level, content, sort_order)
select 'mcq'::exercise_type, 'vocabulary'::skill_area, t.id, v.id, t.cefr_level, gen.content::jsonb, gen.sort_order
from (values
${mcqRows.join(",\n")}
) as gen(topic_slug, headword, content, sort_order)
join public.topics t on t.slug = gen.topic_slug
join public.vocabulary_items v on v.topic_id = t.id and v.headword = gen.headword;
`);

// Two match exercises per topic (words 1–5 and 6–10).
const matchRows = [];
for (const t of VOCAB_TOPICS) {
  [t.words.slice(0, 5), t.words.slice(5, 10)].forEach((group, k) => {
    if (group.length < 3) return;
    matchRows.push(`  (${q(t.slug)}, ${json({ pairs: group.map((w) => ({ left: w[0], right: w[3] })) })}, ${100 + k})`);
  });
}
out.push(`insert into public.exercises (type, skill_area, topic_id, cefr_level, content, sort_order)
select 'match'::exercise_type, 'vocabulary'::skill_area, t.id, t.cefr_level, gen.content::jsonb, gen.sort_order
from (values
${matchRows.join(",\n")}
) as gen(topic_slug, content, sort_order)
join public.topics t on t.slug = gen.topic_slug;
`);

// Grammar
const gSlugs = GRAMMAR_TOPICS.map((g) => q(g.slug)).join(", ");
out.push(`insert into public.grammar_topics (slug, name_he, name_en, cefr_level, sort_order) values
${GRAMMAR_TOPICS.map((g) => `  (${q(g.slug)}, ${q(g.name_he)}, ${q(g.name_en)}, ${q(g.level)}, ${g.sort})`).join(",\n")}
on conflict (slug) do update set
  name_he = excluded.name_he,
  name_en = excluded.name_en,
  cefr_level = excluded.cefr_level,
  sort_order = excluded.sort_order;

delete from public.grammar_lessons where grammar_topic_id in (select id from public.grammar_topics where slug in (${gSlugs}));
delete from public.exercises where grammar_topic_id in (select id from public.grammar_topics where slug in (${gSlugs}));
`);
out.push(`insert into public.grammar_lessons (grammar_topic_id, title_he, body_md, cefr_level, sort_order)
select gt.id, l.title_he, l.body_md, gt.cefr_level, 1
from public.grammar_topics gt
join (values
${GRAMMAR_TOPICS.map((g) => `  (${q(g.slug)}, ${q(g.title_he)}, ${dollar(g.body_md)})`).join(",\n")}
) as l(slug, title_he, body_md) on gt.slug = l.slug;
`);
const fillRows = GRAMMAR_TOPICS.flatMap((g) =>
  g.fill.map(([sentence, correctAnswer, hint], i) => `  (${q(g.slug)}, ${json({ sentence, correctAnswer, hint })}, ${i + 1})`),
);
out.push(`insert into public.exercises (type, skill_area, grammar_topic_id, cefr_level, content, sort_order)
select 'fill_blank'::exercise_type, 'grammar'::skill_area, gt.id, gt.cefr_level, gen.content::jsonb, gen.sort_order
from (values
${fillRows.join(",\n")}
) as gen(slug, content, sort_order)
join public.grammar_topics gt on gt.slug = gen.slug;
`);
const reorderRows = GRAMMAR_TOPICS.flatMap((g) =>
  g.reorder.map((tokens, i) => `  (${q(g.slug)}, ${json({ tokens, correctOrder: tokens.map((_, k) => k) })}, ${100 + i})`),
);
out.push(`insert into public.exercises (type, skill_area, grammar_topic_id, cefr_level, content, sort_order)
select 'reorder'::exercise_type, 'grammar'::skill_area, gt.id, gt.cefr_level, gen.content::jsonb, gen.sort_order
from (values
${reorderRows.join(",\n")}
) as gen(slug, content, sort_order)
join public.grammar_topics gt on gt.slug = gen.slug;
`);

// Writing prompts
out.push(`insert into public.writing_prompts (title_he, prompt_en, cefr_level, sort_order)
select w.title_he, w.prompt_en, w.lvl::cefr_level, w.sort_order
from (values
${WRITING_PROMPTS.map(([lvl, he, en], i) => `  (${q(he)}, ${q(en)}, ${q(lvl)}, ${10 + i})`).join(",\n")}
) as w(title_he, prompt_en, lvl, sort_order)
where not exists (select 1 from public.writing_prompts p where p.prompt_en = w.prompt_en);
`);

// Scenarios
out.push(`insert into public.conversation_scenarios (slug, title_he, title_en, system_prompt, cefr_level, category, sort_order) values
${SCENARIOS.map(([slug, he, en, lvl, cat, prompt], i) => `  (${q(slug)}, ${q(he)}, ${q(en)}, ${q(prompt)}, ${q(lvl)}, ${q(cat)}, ${200 + i})`).join(",\n")}
on conflict (slug) do update set
  title_he = excluded.title_he,
  title_en = excluded.title_en,
  system_prompt = excluded.system_prompt,
  cefr_level = excluded.cefr_level,
  category = excluded.category,
  sort_order = excluded.sort_order;
`);

const path = new URL("../supabase/seed/026_level_expansion.sql", import.meta.url);
writeFileSync(path, out.join("\n"));
console.log(`wrote ${path.pathname} — ${mcqRows.length} vocab MCQs, ${matchRows.length} matches, ${fillRows.length + reorderRows.length} grammar exercises`);
