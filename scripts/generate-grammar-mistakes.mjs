// Writes supabase/seed/058_grammar_common_mistakes.sql from
// scripts/content/grammarMistakes.mjs: one extra lesson per topic, "the
// mistakes Hebrew speakers make", shown in the app and on the public
// /english-grammar pages. Run: node scripts/generate-grammar-mistakes.mjs
import { writeFileSync } from "node:fs";
import { GRAMMAR_MISTAKES } from "./content/grammarMistakes.mjs";

const TITLE = "טעויות נפוצות של דוברי עברית";
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const dollar = (s) => {
  if (s.includes("$md$")) throw new Error("body contains $md$");
  return `$md$${s}$md$`;
};

const errors = [];
const HEBREW_DASH = /[֐-׿][^\n]{0,25}—|—[^\n]{0,25}[֐-׿]/;
const rows = Object.entries(GRAMMAR_MISTAKES).map(([slug, { intro, mistakes }]) => {
  if (mistakes.length < 3) errors.push(`${slug}: needs at least 3 mistakes`);
  const body = [
    intro,
    ...mistakes.map(
      ([title, wrong, right, why], i) =>
        `**טעות ${i + 1}: ${title}**\n\n- לא נכון: ${wrong}\n- נכון: ${right}\n\nלמה: ${why}`,
    ),
  ].join("\n\n");
  // Every line opens with a Hebrew word: the lesson renderer picks a line's
  // direction from its text, and a line that starts in English is laid out
  // left to right with its Hebrew scrambled.
  for (const line of body.split("\n").filter((l) => l.trim())) {
    const start = line.replace(/^[-*\s\d.]+/, "");
    if (/^[^א-ת]*[A-Za-z]/.test(start.split(/[א-ת]/)[0])) errors.push(`${slug}: line starts in English: ${line}`);
  }
  if (HEBREW_DASH.test(body)) errors.push(`${slug}: long dash next to Hebrew`);
  for (const [, wrong, right] of mistakes) if (wrong === right) errors.push(`${slug}: wrong equals right: ${wrong}`);
  return `  (${q(slug)}, ${dollar(body)})`;
});
if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}

const slugs = Object.keys(GRAMMAR_MISTAKES).map(q).join(", ");
const sql = `-- 058_grammar_common_mistakes (generated by scripts/generate-grammar-mistakes.mjs
-- from scripts/content/grammarMistakes.mjs; edit the content there, not here).
-- A second lesson, "${TITLE}", for ${rows.length} grammar topics whose
-- page was short: each mistake shown wrong, then right, with the reason.
-- Shown in the app's topic page and on /english-grammar/<slug>. All content
-- is original (2026-11-18).
-- Safe to re-run: this lesson is deleted and reinserted by title. Note that
-- re-running seeds 031/032 (which clear a topic's lessons) removes it; run
-- this one again after them.

delete from public.grammar_lessons
where title_he = ${q(TITLE)}
  and grammar_topic_id in (select id from public.grammar_topics where slug in (${slugs}));

insert into public.grammar_lessons (grammar_topic_id, title_he, body_md, cefr_level, sort_order)
select gt.id, ${q(TITLE)}, l.body_md, gt.cefr_level, 90
from public.grammar_topics gt
join (values
${rows.join(",\n")}
) as l(slug, body_md) on gt.slug = l.slug;

-- Check: should be ${rows.length}.
select count(*) as mistakes_lessons
from public.grammar_lessons
where title_he = ${q(TITLE)};
`;
writeFileSync(new URL("../supabase/seed/058_grammar_common_mistakes.sql", import.meta.url), sql);
console.log(`wrote 058 with ${rows.length} lessons`);
