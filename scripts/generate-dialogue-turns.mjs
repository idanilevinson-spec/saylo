// Writes a seed that rewrites conversation clips as A:/B: turns, from
// scripts/content/dialogueTurns.mjs. Refuses to write anything unless the
// turns, joined back together, are exactly the clip's current words
// (after the listed wording fixes), so no dictation or question breaks.
// Run: node scripts/generate-dialogue-turns.mjs <seed name>
import { readFileSync, writeFileSync } from "node:fs";
import { createClient } from "@supabase/supabase-js";
import { DIALOGUE_TURNS, WORDING_FIXES } from "./content/dialogueTurns.mjs";

const seedName = process.argv[2];
if (!seedName) throw new Error("usage: node scripts/generate-dialogue-turns.mjs <seed name>");
const env = Object.fromEntries(
  readFileSync(new URL("../.env.local", import.meta.url), "utf8")
    .split(/\r?\n/)
    .filter((l) => l.includes("=") && !l.startsWith("#"))
    .map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1).replace(/^"|"$/g, "")]),
);
const sb = createClient(env.NEXT_PUBLIC_SUPABASE_URL, env.SUPABASE_SERVICE_ROLE_KEY);
const { data: clips, error } = await sb.from("listening_clips").select("id, title_en, transcript_en");
if (error) throw error;

const squash = (s) => s.replace(/\s+/g, " ").trim();
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const errors = [];
const updates = [];
for (const [title, turns] of Object.entries(DIALOGUE_TURNS)) {
  const clip = clips.find((c) => c.title_en === title);
  if (!clip) {
    errors.push(`${title}: no such clip`);
    continue;
  }
  if (turns.length < 2 || !turns.every((t) => /^[AB]: \S/.test(t))) errors.push(`${title}: every turn must start with "A: " or "B: "`);
  turns.forEach((t, i) => i && t[0] === turns[i - 1][0] && errors.push(`${title}: two turns in a row by ${t[0]}`));
  let expected = clip.transcript_en;
  for (const [from, to] of WORDING_FIXES[title] ?? []) {
    if (!expected.includes(from)) errors.push(`${title}: wording fix "${from}" not found`);
    expected = expected.replace(from, to);
  }
  const joined = turns.map((t) => t.slice(3)).join(" ");
  if (squash(joined) !== squash(expected)) errors.push(`${title}: turns don't add up to the transcript`);
  updates.push(`update public.listening_clips set transcript_en = ${q(turns.join("\n"))} where id = ${q(clip.id)};`);
}
if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}
const titles = Object.keys(DIALOGUE_TURNS).map(q).join(", ");
writeFileSync(
  new URL(`../supabase/seed/${seedName}.sql`, import.meta.url),
  `-- ${seedName}.sql (generated by scripts/generate-dialogue-turns.mjs from
-- scripts/content/dialogueTurns.mjs; edit the content there).
-- ${updates.length} conversation clips rewritten as one turn per line ("A: ..."),
-- so each speaker is read by a different voice. Same words; learners'
-- answers are kept. Safe to re-run.

${updates.join("\n")}

-- Check: clips now written as turns (should be ${updates.length}).
select count(*) as dialogue_clips from public.listening_clips
where title_en in (${titles}) and (transcript_en like 'A: %' or transcript_en like 'B: %');
`,
);
console.log(`wrote supabase/seed/${seedName}.sql: ${updates.length} clips`);
