// Writes a seed that updates existing fill-in exercises in place from
// scripts/content/fillAlternatives.mjs: accepted answers, a clearer
// sentence or a Hebrew hint. Every id prefix must match exactly one
// fill-in whose current answer is the one written in the content file.
// Run: node scripts/generate-fill-fixes.mjs <seed name>
import { readFileSync, writeFileSync } from "node:fs";
import { createClient } from "@supabase/supabase-js";
import { FILL_FIXES } from "./content/fillAlternatives.mjs";

const seedName = process.argv[2];
if (!seedName) {
  console.error("usage: node scripts/generate-fill-fixes.mjs <seed name>");
  process.exit(1);
}

const env = Object.fromEntries(
  readFileSync(new URL("../.env.local", import.meta.url), "utf8")
    .split(/\r?\n/)
    .filter((l) => l.includes("=") && !l.startsWith("#"))
    .map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1).replace(/^"|"$/g, "")]),
);
const sb = createClient(env.NEXT_PUBLIC_SUPABASE_URL, env.SUPABASE_SERVICE_ROLE_KEY);

let rows = [];
for (let from = 0; ; from += 1000) {
  const { data, error } = await sb.from("exercises").select("id, content").eq("type", "fill_blank").order("id").range(from, from + 999);
  if (error) throw error;
  rows = rows.concat(data);
  if (data.length < 1000) break;
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const errors = [];
const updates = [];
for (const [prefix, fix] of Object.entries(FILL_FIXES)) {
  const matches = rows.filter((r) => r.id.startsWith(prefix));
  if (matches.length !== 1) {
    errors.push(`${prefix}: ${matches.length} matches`);
    continue;
  }
  const [row] = matches;
  if (row.content.correctAnswer !== fix.answer) {
    errors.push(`${prefix}: answer is "${row.content.correctAnswer}", not "${fix.answer}"`);
    continue;
  }
  if (fix.sentence && !fix.sentence.includes("___")) errors.push(`${prefix}: sentence has no blank`);
  if (fix.hint && /—/.test(fix.hint)) errors.push(`${prefix}: long dash in hint`);
  const accepted = fix.accepted ?? [];
  if (accepted.some((a) => a.toLowerCase() === fix.answer.toLowerCase())) errors.push(`${prefix}: answer repeated in accepted`);
  if (new Set(accepted).size !== accepted.length) errors.push(`${prefix}: duplicate accepted answer`);

  const patch = {};
  if (accepted.length) patch.acceptedAnswers = accepted;
  if (fix.sentence) patch.sentence = fix.sentence;
  if (fix.hint) patch.hint = fix.hint;
  updates.push(`update public.exercises set content = content || ${q(JSON.stringify(patch))}::jsonb where id = ${q(row.id)};`);
}
if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}

const ids = Object.keys(FILL_FIXES).map((p) => rows.find((r) => r.id.startsWith(p)).id);
const out = `-- ${seedName}.sql (generated by scripts/generate-fill-fixes.mjs from
-- scripts/content/fillAlternatives.mjs; edit the content there).
-- ${updates.length} fill-in exercises updated in place: other right answers
-- they now accept, clearer sentences, and Hebrew hints. Learners' past
-- answers are kept. Safe to re-run.

${updates.join("\n")}

-- Check: how many of these now carry the change.
select
  (select count(*) from public.exercises where id in (${ids.map(q).join(", ")})) as exercises,
  (select count(*) from public.exercises where id in (${ids.map(q).join(", ")}) and content ? 'acceptedAnswers') as with_accepted_answers;
`;
writeFileSync(new URL(`../supabase/seed/${seedName}.sql`, import.meta.url), out);
const withAccepted = Object.values(FILL_FIXES).filter((f) => f.accepted?.length).length;
console.log(`wrote supabase/seed/${seedName}.sql: ${updates.length} updates, ${withAccepted} with accepted answers`);
