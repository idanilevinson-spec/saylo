// Writes a seed that splits lesson lines of the form "**Hebrew label:** an
// English run" into the label on its own line and the English as its own
// paragraph. In one line the English list ("arguably, apparently, probably,
// to some extent, in most cases") wrapped inside a right-to-left paragraph
// and broke apart on narrow screens; on its own line it is laid out left to
// right like every other example (see lessonLineDir in
// GrammarLessonContent). Only those lines change; the words stay the same.
// Run: node scripts/generate-lesson-line-split.mjs <seed name>
import { readFileSync, writeFileSync } from "node:fs";
import { createClient } from "@supabase/supabase-js";

const seedName = process.argv[2];
if (!seedName) throw new Error("usage: node scripts/generate-lesson-line-split.mjs <seed name>");
const env = Object.fromEntries(
  readFileSync(new URL("../.env.local", import.meta.url), "utf8")
    .split(/\r?\n/)
    .filter((l) => l.includes("=") && !l.startsWith("#"))
    .map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1).replace(/^"|"$/g, "")]),
);
const sb = createClient(env.NEXT_PUBLIC_SUPABASE_URL, env.SUPABASE_SERVICE_ROLE_KEY);
const { data: lessons, error } = await sb.from("grammar_lessons").select("id, body_md");
if (error) throw error;

const LINE = /^(\*\*[^*]*[\u0590-\u05FF][^*]*\*\*:?)\s+([^\u0590-\u05FF]{21,})$/;
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const updates = [];
let lines = 0;
for (const l of lessons) {
  const nl = l.body_md.includes("\r\n") ? "\r\n" : "\n";
  let changed = false;
  const body = l.body_md
    .split(/\r?\n/)
    .map((line) => {
      const m = line.match(LINE);
      if (!m) return line;
      changed = true;
      lines++;
      return `${m[1]}${nl}${nl}${m[2]}`;
    })
    .join(nl);
  // Same words, only line breaks added.
  if (changed && body.replace(/\s+/g, " ") !== l.body_md.replace(/\s+/g, " ")) throw new Error(`${l.id}: words changed`);
  if (changed) updates.push(`update public.grammar_lessons set body_md = ${q(body)} where id = ${q(l.id)};`);
}
writeFileSync(
  new URL(`../supabase/seed/${seedName}.sql`, import.meta.url),
  `-- ${seedName}.sql (generated by scripts/generate-lesson-line-split.mjs).
-- ${lines} lesson lines in ${updates.length} lessons: a Hebrew label followed by an English run
-- now puts the English on its own line. Same words. Safe to re-run (a split
-- line no longer matches).

${updates.join("\n")}

-- Check: lessons updated (should be ${updates.length}).
select count(*) as lessons from public.grammar_lessons where id in (${updates.map((u) => u.match(/where id = ('[^']+')/)[1]).join(", ")});
`,
);
console.log(`wrote supabase/seed/${seedName}.sql: ${lines} lines in ${updates.length} lessons`);
