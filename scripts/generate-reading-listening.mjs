// Writes supabase/seed/027_reading_listening_b1_c2.sql from
// scripts/content/readingListening.mjs. Validates every question before
// writing anything. Run: node scripts/generate-reading-listening.mjs
import { writeFileSync } from "node:fs";
// Optional args: content module (default readingListening.mjs) and seed
// file name, so the same validation serves every reading/listening batch.
const contentPath = process.argv[2] ?? "./content/readingListening.mjs";
const seedName = process.argv[3] ?? "027_reading_listening_b1_c2.sql";
const { READING = [], LISTENING = [], IDIOMS = [], EXISTING_LISTENING_MCQ = {} } = await import(
  new URL(contentPath, import.meta.url).href
);

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const json = (o) => q(JSON.stringify(o));
const errors = [];

function checkMcq(where, [prompt, options, correct]) {
  if (!prompt) errors.push(`${where}: empty prompt`);
  if (options.length !== 4) errors.push(`${where}: needs 4 options`);
  if (new Set(options).size !== options.length) errors.push(`${where}: duplicate options`);
  if (!(correct >= 0 && correct < options.length)) errors.push(`${where}: bad correctIndex`);
}
for (const r of READING) {
  if (r.body.split(/\s+/).length < (r.level.startsWith("A") ? 150 : 250)) errors.push(`${r.title_en}: body too short`);
  r.mcq.forEach((m, i) => checkMcq(`${r.title_en} q${i + 1}`, m));
}
for (const l of LISTENING) {
  l.mcq.forEach((m, i) => checkMcq(`${l.title_en} q${i + 1}`, m));
  if (!l.dictation || l.dictation.split(" ").length < 4) errors.push(`${l.title_en}: dictation too short`);
}
for (const [title, qs] of Object.entries(EXISTING_LISTENING_MCQ)) qs.forEach((m, i) => checkMcq(`${title} q${i + 1}`, m));
const titles = [...READING, ...LISTENING].map((x) => x.title_en);
if (new Set(titles).size !== titles.length) errors.push("duplicate titles");
if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}

// Spread correct answers across positions: rotate each question's options
// so its correct answer lands on (question index % 4), keeping order.
function rotate([prompt, options, correct], i) {
  const target = i % 4;
  const shift = (target - correct + 4) % 4;
  const rotated = options.map((_, k) => options[(k - shift + 4) % 4]);
  if (rotated[target] !== options[correct]) throw new Error("rotation bug");
  return { prompt, options: rotated, correctIndex: target };
}

const readingTitles = READING.map((r) => q(r.title_en)).join(", ");
const listeningTitles = LISTENING.map((l) => q(l.title_en)).join(", ");
const existingTitles = Object.keys(EXISTING_LISTENING_MCQ);
const out = [];
out.push(`-- ${seedName} (generated by scripts/generate-reading-listening.mjs from
-- ${contentPath.replace(/^\.\//, "scripts/")}; edit the content there).
-- ${READING.length} original reading texts (MCQ + open questions each),
-- ${LISTENING.length} listening clips (MCQ + 1 dictation each)${existingTitles.length ? `, and comprehension
-- questions for ${existingTitles.length} existing clips` : ""}.
-- Safe to re-run: rows with these titles are deleted first; their
-- exercises and open questions cascade.
`);

if (READING.length)
  out.push(`delete from public.reading_texts where title_en in (${readingTitles});

insert into public.reading_texts (title_he, title_en, body_en, cefr_level, sort_order) values
${READING.map((r, i) => `  (${q(r.title_he)}, ${q(r.title_en)}, ${q(r.body)}, ${q(r.level)}, ${100 + i})`).join(",\n")};

insert into public.exercises (type, skill_area, reading_text_id, cefr_level, content, sort_order)
select 'mcq'::exercise_type, 'reading'::skill_area, rt.id, rt.cefr_level, gen.content::jsonb, gen.sort_order
from public.reading_texts rt
join (values
${READING.flatMap((r) => r.mcq.map((m, i) => `  (${q(r.title_en)}, ${json(rotate(m, i))}, ${i + 1})`)).join(",\n")}
) as gen(title_en, content, sort_order)
  on rt.title_en = gen.title_en;

insert into public.reading_open_questions (reading_text_id, question_en, sort_order)
select rt.id, gen.question_en, gen.sort_order
from public.reading_texts rt
join (values
${READING.flatMap((r) => r.open.map((oq, i) => `  (${q(r.title_en)}, ${q(oq)}, ${i + 1})`)).join(",\n")}
) as gen(title_en, question_en, sort_order)
  on rt.title_en = gen.title_en;
`);

if (LISTENING.length)
  out.push(`delete from public.listening_clips where title_en in (${listeningTitles});

insert into public.listening_clips (title_he, title_en, transcript_en, cefr_level, style, sort_order) values
${LISTENING.map((l, i) => `  (${q(l.title_he)}, ${q(l.title_en)}, ${q(l.transcript)}, ${q(l.level)}, 'standard', ${100 + i})`).join(",\n")};

insert into public.exercises (type, skill_area, listening_clip_id, cefr_level, content, sort_order)
select 'mcq'::exercise_type, 'listening'::skill_area, lc.id, lc.cefr_level, gen.content::jsonb, gen.sort_order
from public.listening_clips lc
join (values
${LISTENING.flatMap((l) => l.mcq.map((m, i) => `  (${q(l.title_en)}, ${json(rotate(m, i + 1))}, ${i + 2})`)).join(",\n")}
) as gen(title_en, content, sort_order)
  on lc.title_en = gen.title_en;

insert into public.exercises (type, skill_area, listening_clip_id, cefr_level, content, sort_order)
select 'dictation'::exercise_type, 'listening'::skill_area, lc.id, lc.cefr_level, gen.content::jsonb, 1
from public.listening_clips lc
join (values
${LISTENING.map((l) => `  (${q(l.title_en)}, ${json({ audioText: l.dictation, correctAnswer: l.dictation })})`).join(",\n")}
) as gen(title_en, content)
  on lc.title_en = gen.title_en;
`);

// Questions added to clips that already exist. Cleared first by prompt so a
// re-run doesn't duplicate them; the clip's own dictation is left alone.
if (existingTitles.length) {
  const rows = existingTitles.flatMap((title) =>
    EXISTING_LISTENING_MCQ[title].map((m, i) => `  (${q(title)}, ${json(rotate(m, i + 1))}, ${i + 2})`),
  );
  const prompts = existingTitles.flatMap((t) => EXISTING_LISTENING_MCQ[t].map(([p]) => q(p))).join(", ");
  out.push(`delete from public.exercises e using public.listening_clips lc
where e.listening_clip_id = lc.id and e.type = 'mcq' and lc.title_en in (${existingTitles.map(q).join(", ")})
  and e.content->>'prompt' in (${prompts});

insert into public.exercises (type, skill_area, listening_clip_id, cefr_level, content, sort_order)
select 'mcq'::exercise_type, 'listening'::skill_area, lc.id, lc.cefr_level, gen.content::jsonb, gen.sort_order
from public.listening_clips lc
join (values
${rows.join(",\n")}
) as gen(title_en, content, sort_order)
  on lc.title_en = gen.title_en;
`);
}

const allClips = [...LISTENING.map((l) => l.title_en), ...existingTitles];
if (allClips.length)
  out.push(`-- Check: clips from this seed, and their questions.
select
  (select count(*) from public.listening_clips where title_en in (${LISTENING.map((l) => q(l.title_en)).join(", ") || "null"})) as new_clips,
  (select count(*) from public.exercises e join public.listening_clips lc on lc.id = e.listening_clip_id
     where e.type = 'mcq' and lc.title_en in (${allClips.map(q).join(", ")})) as listening_questions;
`);

if (seedName.startsWith("027")) {
// Tidy existing content: lesson titles lose the long dash, and three
// listening questions drop "/ה" forms for neutral Hebrew (the site-wide
// rule). Profession translations such as "נהג/ת" stay: that is the normal
// dictionary way to translate a gender-neutral English noun.
out.push(`-- ============ Tidy existing content ============
update public.grammar_lessons set title_he = replace(title_he, ' — ', ': ') where title_he like '% — %';

update public.exercises set content = ${json({ prompt: 'מה מתאר הדובר כשהוא אומר "I\'m kinda swamped"?', options: ["המון עבודה", "רעב", "בלבול", "איחור"], correctIndex: 0 })}::jsonb
where skill_area = 'listening' and content->>'prompt' = ${q('מה המשמעות של "I\'m kinda swamped" בהקשר הזה?')};

update public.exercises set content = ${json({ prompt: "איך הגיב מקום העבודה לאיחור, לפי מה שנאמר?", options: ["הכעס היה גדול", "אמרו שזה בסדר ואפשר להגיע כשמסתדר", "ביקשו לא לבוא היום", "לא ענו לטלפון"], correctIndex: 1 })}::jsonb
where skill_area = 'listening' and content->>'prompt' = ${q("איך הגיב מקום העבודה למי שאיחר, לפי מה שנאמר?")};

update public.exercises set content = jsonb_set(content, '{options,3}', ${q(JSON.stringify("זה זכור לי מצוין"))}::jsonb)
where skill_area = 'listening' and content->>'prompt' = ${q('מה המשמעות של "I kinda forgot about that"?')};
`);

}

if (IDIOMS.length) {
  const phrases = IDIOMS.map((i) => q(i[0])).join(", ");
  out.push(`-- ============ Idioms and phrasal verbs ============
delete from public.idioms_phrasal_verbs where phrase in (${phrases});
insert into public.idioms_phrasal_verbs (phrase, type, meaning_he, example_en, cefr_level, sort_order) values
${IDIOMS.map(([phrase, type, he, ex, lvl], i) => `  (${q(phrase)}, ${q(type)}, ${q(he)}, ${q(ex)}, ${q(lvl)}, ${200 + i})`).join(",\n")};
`);
}

const path = new URL(`../supabase/seed/${seedName}`, import.meta.url);
writeFileSync(path, out.join("\n"));
console.log(`wrote ${seedName}: ${READING.length} texts, ${LISTENING.length} clips, ${Object.keys(EXISTING_LISTENING_MCQ).length} existing clips with new questions, ${IDIOMS.length} idioms`);
