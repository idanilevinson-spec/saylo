// Writes a seed that adds word-matching exercises so every word of a
// vocabulary topic appears in at least one. Many topics had a single set of
// four pairs, which left six of their ten words out of matching practice.
// New sets take the uncovered words, four at a time; a last short set is
// topped up with words already used. Pairs come straight from
// vocabulary_items, and a set never holds two words with the same Hebrew
// (that would make the match ambiguous).
// Run: node scripts/generate-match-coverage.mjs <seed name>
import { readFileSync, writeFileSync } from "node:fs";
import { createClient } from "@supabase/supabase-js";

const seedName = process.argv[2];
if (!seedName) throw new Error("usage: node scripts/generate-match-coverage.mjs <seed name>");
const env = Object.fromEntries(
  readFileSync(new URL("../.env.local", import.meta.url), "utf8")
    .split(/\r?\n/)
    .filter((l) => l.includes("=") && !l.startsWith("#"))
    .map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1).replace(/^"|"$/g, "")]),
);
const sb = createClient(env.NEXT_PUBLIC_SUPABASE_URL, env.SUPABASE_SERVICE_ROLE_KEY);
const [{ data: topics }, { data: words }, { data: matches }] = await Promise.all([
  sb.from("topics").select("id, name_he, cefr_level"),
  sb.from("vocabulary_items").select("id, topic_id, headword, translation_he, sort_order").eq("status", "published"),
  sb.from("exercises").select("topic_id, content, sort_order").eq("type", "match"),
]);

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const rows = [];
for (const t of topics) {
  const tw = words.filter((w) => w.topic_id === t.id).sort((a, b) => a.sort_order - b.sort_order);
  if (tw.length < 4) continue;
  const existing = matches.filter((m) => m.topic_id === t.id);
  const covered = new Set(existing.flatMap((m) => m.content.pairs.map((p) => p.left.toLowerCase())));
  const uncovered = tw.filter((w) => !covered.has(w.headword.toLowerCase()));
  let sort = Math.max(0, ...existing.map((m) => m.sort_order ?? 0));
  while (uncovered.length) {
    const set = uncovered.splice(0, 4);
    for (const w of tw) {
      if (set.length === 4) break;
      if (!set.includes(w)) set.push(w);
    }
    const he = set.map((w) => w.translation_he.trim());
    if (new Set(he).size !== he.length) throw new Error(`${t.name_he}: two words share a Hebrew translation`);
    const pairs = set.map((w) => ({ left: w.headword, right: w.translation_he.trim() }));
    rows.push(`  (${q(t.id)}, ${q(t.cefr_level)}, ${q(JSON.stringify({ pairs }))}, ${++sort})`);
  }
}

writeFileSync(
  new URL(`../supabase/seed/${seedName}.sql`, import.meta.url),
  `-- ${seedName}.sql (generated by scripts/generate-match-coverage.mjs).
-- ${rows.length} word-matching exercises so every vocabulary topic's words
-- each appear in at least one. Pairs are the words' own translations.
-- Not idempotent: run once (re-running the generator afterwards adds none).

insert into public.exercises (type, skill_area, topic_id, cefr_level, content, sort_order)
select 'match'::exercise_type, 'vocabulary'::skill_area, gen.topic_id::uuid, gen.cefr_level, gen.content::jsonb, gen.sort_order
from (values
${rows.join(",\n")}
) as gen(topic_id, cefr_level, content, sort_order);

-- Check: match exercises in total (was ${matches.length}, should now be ${matches.length + rows.length}).
select count(*) as match_exercises from public.exercises where type = 'match';
`,
);
console.log(`wrote supabase/seed/${seedName}.sql: ${rows.length} new match sets (was ${matches.length})`);
