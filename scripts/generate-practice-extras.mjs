// Writes a seed of writing prompts and idioms/phrasal verbs from an
// authored content module, plus any one-off text fixes it lists.
// Run: node scripts/generate-practice-extras.mjs scripts/content/practiceSet2.mjs 033_writing_idioms_set_2
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { createClient } from "@supabase/supabase-js";

const [modulePath, seedName] = process.argv.slice(2);
if (!modulePath || !seedName) {
  console.error("usage: node scripts/generate-practice-extras.mjs <content module> <seed name>");
  process.exit(1);
}
const { WRITING_PROMPTS = [], IDIOMS = [], FIXES = [] } = await import(pathToFileURL(modulePath).href);

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const LEVELS = ["A1", "A2", "B1", "B2", "C1", "C2"];
const TYPES = ["idiom", "phrasal_verb"];
const norm = (s) => s.toLowerCase().replace(/[^a-z' -]/g, " ");
const stem = (w) => (w.length > 4 ? w.slice(0, w.length - 2) : w.replace(/[ey]$/, ""));

// ---- validation ----
const errors = [];
const seenPrompts = new Set();
for (const [lvl, he, en] of WRITING_PROMPTS) {
  if (!LEVELS.includes(lvl)) errors.push(`prompt "${he}": bad level`);
  if (!he?.trim() || !en?.trim()) errors.push(`prompt "${he}": missing text`);
  if (he.includes("—")) errors.push(`prompt "${he}": long dash`);
  if (seenPrompts.has(en)) errors.push(`duplicate prompt: ${en}`);
  seenPrompts.add(en);
}
const seenPhrases = new Set();
for (const [lvl, type, phrase, he, ex] of IDIOMS) {
  if (!LEVELS.includes(lvl)) errors.push(`${phrase}: bad level`);
  if (!TYPES.includes(type)) errors.push(`${phrase}: bad type ${type}`);
  if (!he?.trim() || !ex?.trim()) errors.push(`${phrase}: missing text`);
  if (he.includes("—")) errors.push(`${phrase}: long dash`);
  const key = phrase.toLowerCase();
  if (seenPhrases.has(key)) errors.push(`duplicate phrase: ${phrase}`);
  seenPhrases.add(key);
  // Irregular forms ("ran") defeat a stem match, so any content word will do.
  const words = key.split(/\s+/).filter((w) => w.length >= 2 && !["to", "the", "a", "an"].includes(w));
  if (!words.some((w) => norm(ex).includes(stem(w)))) errors.push(`${phrase}: example doesn't use the phrase`);
}

const envPath = new URL("../.env.local", import.meta.url);
if (existsSync(envPath)) {
  const env = Object.fromEntries(
    readFileSync(envPath, "utf8")
      .split(/\r?\n/)
      .filter((l) => l.includes("=") && !l.startsWith("#"))
      .map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1).replace(/^"|"$/g, "")]),
  );
  const sb = createClient(env.NEXT_PUBLIC_SUPABASE_URL, env.SUPABASE_SERVICE_ROLE_KEY);
  const [{ data: ph, error: e1 }, { data: wp, error: e2 }] = await Promise.all([
    sb.from("idioms_phrasal_verbs").select("phrase"),
    sb.from("writing_prompts").select("prompt_en,title_he"),
  ]);
  if (e1 || e2) throw e1 ?? e2;
  const takenPhrases = new Set(ph.map((r) => r.phrase.toLowerCase().replace(/^to /, "")));
  const takenTitles = new Set(wp.map((r) => r.title_he));
  for (const [, , phrase] of IDIOMS)
    if (takenPhrases.has(phrase.toLowerCase().replace(/^to /, ""))) errors.push(`${phrase}: already in the database`);
  for (const [, he] of WRITING_PROMPTS) if (takenTitles.has(he)) errors.push(`prompt title "${he}" already in the database`);
}

if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}

// ---- SQL ----
const count = (rows) => LEVELS.map((l) => `${l}: ${rows.filter((r) => r[0] === l).length}`).join(", ");
const out = [];
out.push(`-- ${seedName} (generated by scripts/generate-practice-extras.mjs from
-- ${modulePath.replace(/\\/g, "/")}; edit the content there, not here).
-- ${WRITING_PROMPTS.length} writing prompts (${count(WRITING_PROMPTS)}),
-- ${IDIOMS.length} idioms and phrasal verbs (${count(IDIOMS)}).
-- All content is original. Safe to re-run: rows are inserted only if the
-- same prompt or phrase isn't there yet.
`);
if (WRITING_PROMPTS.length)
  out.push(`insert into public.writing_prompts (title_he, prompt_en, cefr_level, sort_order)
select w.title_he, w.prompt_en, w.lvl::cefr_level, w.sort_order
from (values
${WRITING_PROMPTS.map(([lvl, he, en], i) => `  (${q(he)}, ${q(en)}, ${q(lvl)}, ${100 + i})`).join(",\n")}
) as w(title_he, prompt_en, lvl, sort_order)
where not exists (select 1 from public.writing_prompts p where p.prompt_en = w.prompt_en);
`);
if (IDIOMS.length)
  out.push(`insert into public.idioms_phrasal_verbs (phrase, type, meaning_he, example_en, cefr_level, sort_order)
select i.phrase, i.type::idiom_type, i.meaning_he, i.example_en, i.lvl::cefr_level, i.sort_order
from (values
${IDIOMS.map(([lvl, type, phrase, he, ex], i) => `  (${q(phrase)}, ${q(type)}, ${q(he)}, ${q(ex)}, ${q(lvl)}, ${100 + i})`).join(",\n")}
) as i(phrase, type, meaning_he, example_en, lvl, sort_order)
where not exists (select 1 from public.idioms_phrasal_verbs x where lower(x.phrase) = lower(i.phrase));
`);
for (const f of FIXES)
  out.push(`update public.${f.table} set ${f.column} = ${q(f.to)} where ${f.column} = ${q(f.from)};`);

out.push(`
-- Check: prompts and phrases from this seed that are now in the tables.
select
  (select count(*) from public.writing_prompts where prompt_en in (${WRITING_PROMPTS.map(([, , en]) => q(en)).join(", ")})) as writing_prompts,
  (select count(*) from public.idioms_phrasal_verbs where phrase in (${IDIOMS.map(([, , p]) => q(p)).join(", ")})) as idioms;
`);

const path = new URL(`../supabase/seed/${seedName}.sql`, import.meta.url);
writeFileSync(path, out.join("\n"));
console.log(`wrote supabase/seed/${seedName}.sql: ${WRITING_PROMPTS.length} prompts, ${IDIOMS.length} idioms, ${FIXES.length} fixes`);
